function r=fitTrends(t,c)
spec={'CruiseYear','Year','Cruise_kmh',c.designYear;'RangeYear','Year','Range_km',c.designYear; ...
 'PayloadYear','Year','PayloadFraction',c.designYear; ...
 'SpeedPower','PowerLoading_kWkg','Cruise_kmh',c.powerLoading_kWkg; ...
 'SpeedWing','WingLoading_Nm2','Cruise_kmh',c.wingLoading_Nm2; ...
 'RangeAR','AspectRatio','Range_km',c.aspectRatio; ...
 'PayloadEmpty','EmptyFraction','PayloadFraction',NaN};
for k=1:size(spec,1)
    x=t.(spec{k,2}); y=t.(spec{k,3}); use=t.TrendEligible&isfinite(x)&isfinite(y);
    assert(nnz(use)>=3,'ffstudio:Trend','Each fit needs at least 3 finite observations.');
    p=polyfit(x(use),y(use),1); yh=polyval(p,x(use)); ss=sum((y(use)-mean(y(use))).^2);
    r.(spec{k,1})=struct('slope',p(1),'intercept',p(2),'n',nnz(use), ...
        'R2',1-sum((y(use)-yh).^2)/max(ss,eps),'prediction',polyval(p,spec{k,4}), ...
        'IDs',t.ID(use),'x',x(use),'y',y(use),'xName',spec{k,2},'yName',spec{k,3});
end
use=t.EmptyEligible & t.EmptyFraction>0;
p=polyfit(log(t.MTOW_kg(use)),log(t.EmptyFraction(use)),1);
r.EmptyLaw=struct('A',exp(p(2)),'C',p(1),'n',nnz(use),'IDs',t.ID(use), ...
    'mass_kg',t.MTOW_kg(use),'fraction',t.EmptyFraction(use));
end
